SXEM = """\
sxem Məktəb
    cədvəl tələbələr
        id: tam açar
        ad: mətn məcburi
        sinif: tam = 1
        aktiv: məntiq = doğru
        qrup_id: tam → qruplar.id
    son
    cədvəl qruplar
        id: tam açar
        ad: mətn məcburi tək
    son
son
"""


def _oxu(m: str):
    x = XətaToplayıcı()
    return S.mətndən(m, "m.sxem", x), x


class Sxem(unittest.TestCase):
    def test_oxuma_yazma_dövrəsi(self):
        s, x = _oxu(SXEM)
        self.assertTrue(x.uğurludur(), x.hesabat(False))
        self.assertEqual([c.ad for c in s.cədvəllər], ["tələbələr", "qruplar"])
        t = s.cədvəl("tələbələr")
        self.assertEqual(t.açar().ad, "id")
        self.assertEqual(t.sahə("qrup_id").əlaqə, ("qruplar", "id"))
        self.assertEqual(t.sahə("sinif").standart, 1)
        self.assertEqual(S.yaz(_oxu(S.yaz(s))[0]), S.yaz(s))

    def test_lüğət_dövrəsi(self):
        s, _ = _oxu(SXEM)
        self.assertEqual(S.yaz(S.lüğətdən(s.lüğət())), S.yaz(s))

    def test_ddl_üç_baza(self):
        s, _ = _oxu(SXEM)
        sqlite = S.ddl(s, "sqlite")
        # əlaqə sırası: istinad olunan cədvəl əvvəl
        self.assertIn('"qruplar"', sqlite[0])
        self.assertIn("AUTOINCREMENT", sqlite[0])
        self.assertIn('FOREIGN KEY ("qrup_id") REFERENCES "qruplar"',
                      sqlite[1])
        self.assertIn("GENERATED BY DEFAULT AS IDENTITY",
                      S.ddl(s, "postgres")[0])
        my = S.ddl(s, "mysql")[0]
        self.assertIn("AUTO_INCREMENT", my)
        self.assertIn("`ad` VARCHAR(255) NOT NULL UNIQUE", my)

    def test_tətbiq_et_çatışmayanı_yaradır_heç_nə_silmir(self):
        s, _ = _oxu(SXEM)
        b = bağlan("sqlite::yaddaş:")
        self.assertEqual(len(S.tətbiq_et(b, s)), 2)
        b.icra("INSERT INTO qruplar (ad) VALUES ($1)", "5A")
        s.cədvəl("tələbələr").sahələr.append(S.Sahə("soyad", "mətn"))
        əmrlər = S.tətbiq_et(b, s)
        self.assertEqual(len(əmrlər), 1)
        self.assertIn("ADD COLUMN", əmrlər[0])
        self.assertEqual(S.tətbiq_et(b, s), [])
        self.assertEqual(b.bir_dəyər("SELECT COUNT(*) FROM qruplar"), 1)
        idx = S.idxal(b)
        self.assertEqual(sorted(c.ad for c in idx.cədvəllər),
                         ["qruplar", "tələbələr"])
        self.assertEqual(idx.cədvəl("tələbələr").açar().ad, "id")

    def test_model_kodu_işləyir(self):
        s, _ = _oxu(SXEM)
        kod = S.model_kodu(s)
        self.assertIn('@cədvəl("tələbələr")', kod)
        self.assertIn("sinif Tələbə miras verilənlər.Model", kod)
        self.assertIn("sinif Qrup miras verilənlər.Model", kod)
        with tempfile.TemporaryDirectory() as q:
            q = Path(q)
            (q / "m.alq").write_text(
                kod + 'dəyişən b = verilənlər.bağlan("sqlite::yaddaş:")\n'
                "Qrup.istifadəEt(b)\nQrup.cədvəlYarat()\n"
                'Qrup.yarat({"ad": "5A"})\nyaz(Qrup.say())\n',
                encoding="utf-8")
            r = subprocess.run([sys.executable, str(KÖK / "alqorc.py"),
                                "işlət", str(q / "m.alq")],
                               capture_output=True, text=True,
                               encoding="utf-8", timeout=60,
                               env=dict(os.environ, PYTHONIOENCODING="utf-8"))
            self.assertEqual(r.stdout.strip(), "1", r.stderr)

    def test_xətalar(self):
        hallar = [
            ("sxem A\n    cədvəl t\n        x: tamm\n    son\nson\n",
             "ALQ-D001", "bəlkə `tam`?"),
            ("sxem A\n    cədvəl t\n        x: tam\n        x: mətn\n"
             "    son\nson\n", "ALQ-D003", ""),
            ("sxem A\n    cədvəl t\n        x: tam açar\n        y: tam açar\n"
             "    son\nson\n", "ALQ-D004", ""),
            ("sxem A\n    cədvəl t\n        x: tam → y.z\n    son\nson\n",
             "ALQ-D005", ""),
        ]
        for m, kod, kömək in hallar:
            with self.subTest(kod=kod):
                s, x = _oxu(m)
                self.assertIsNone(s)
                self.assertIn(kod, [d.kod for d in x.siyahı])
                if kömək:
                    self.assertIn(kömək, x.hesabat(False))


