class FormadaBaza(unittest.TestCase):
    def setUp(self):
        self.q = Path(tempfile.mkdtemp(prefix="forma-baza-")).resolve()

    def tearDown(self):
        shutil.rmtree(self.q, ignore_errors=True)

    def test_crud_naviqator_və_bağlama(self):
        (self.q / "mekteb.sxem").write_text(
            "sxem M\n    cədvəl tələbələr\n        id: tam açar\n"
            "        ad: mətn məcburi\n        sinif: tam = 1\n    son\nson\n",
            encoding="utf-8")
        (self.q / "Əsas.forma").write_text(FORMA, encoding="utf-8")
        (self.q / "Əsas.alq").write_text(KOD, encoding="utf-8")
        r = subprocess.run(
            [sys.executable, str(KÖK / "alqorc.py"), "işlət",
             str(self.q / "Əsas.alq")], capture_output=True, text=True,
            encoding="utf-8", timeout=60,
            env=dict(os.environ, PYTHONIOENCODING="utf-8", ALQOR_BASSIZ="1"))
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertEqual(r.stdout.splitlines(),
                         ["doğru doğru", "doğru", "doğru"])
        b = bağlan(f"sqlite://{self.q / 'mekteb.db'}")
        # tip çevrilməsi: sahədən gələn "5" tam kimi yazılıb
        self.assertEqual(b.sorğu("SELECT ad, sinif FROM tələbələr"),
                         [{"ad": "Aysel", "sinif": 5}])

    def test_mənbə_sorğu_olmalıdır(self):
        x = XətaToplayıcı()
        F.mətndən("forma A\n    obyekt S: sahə\n        mənbə = Yox\n"
                  "    son\nson\n", "A.forma", x)
        self.assertIn("ALQ-F008", [d.kod for d in x.siyahı])

    def test_sehrbaz_etibarlı_forma_yaradır(self):
        s, _ = _oxu(SXEM)
        f = F.FormaTəsviri("Əsas")
        f.obyektlər.append(F.ObyektTəsviri("Baza1", "VerilənlərBazası"))
        f.obyektlər += crud_obyektləri(s, "tələbələr")
        x = XətaToplayıcı()
        f2 = F.mətndən(F.yaz(f), "Əsas.forma", x)
        self.assertTrue(x.uğurludur(), x.hesabat(False))
        növlər = {o.ad: o.növ for o in f2.hamısı()}
        self.assertEqual(növlər["Tələbələr"], "Sorğu")
        self.assertEqual(növlər["AdSahəsi"], "sahə")
        self.assertEqual(növlər["AktivSahəsi"], "açar")
        self.assertEqual(növlər["TələbələrNaviqator"], "naviqator")
        # açar sahə (id) üçün giriş yaradılmır
        self.assertNotIn("IdSahəsi", növlər)


if __name__ == "__main__":
    unittest.main()
